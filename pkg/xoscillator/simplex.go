// hash256 is a high-performance 8-bit hash for 2D points with a seed.
func hash256(x, y, s int) int {
    s ^= (x * 0x1827F5) ^ (y * 0x123C21)
    // Replicating the bitwise operations (>>> is unsigned shift in Java, Go uses >>)
    // Since s is used as int, we must ensure correct behavior. In Go, for int, >> is arithmetic shift.
    // However, the original uses `>>>` (logical shift). To replicate this behavior with int, we need to be careful,
    // or cast to uint first. Let's use uint32 for the seed smashing part to match Java's int behavior.
    uS := uint32(s)
    // (s ^ (s << 19 | s >>> 13) ^ (s << 5 | s >>> 27) ^ 0xD1B54A35)
    uS = uS ^ (uS<<19 | uS>>13) ^ (uS<<5 | uS>>27) ^ 0xD1B54A35
    // * 0x125493
    uS = uS * 0x125493
    // >>> 24
    uS = uS >> 24
    return int(uS)
}

// gradCoord2D computes the dot product of a randomly selected gradient vector and the vector
// from the simplex grid corner (x, y) to the evaluation point (xd, yd).
func gradCoord2D(seed, x, y int, xd, yd float64) float64 {
    // Get an 8-bit hash (0-255) to select a gradient vector.
    hash := hash256(x, y, seed)

    // Each vector is 2 doubles, so the index in GRADIENTS_2D is hash * 2.
    idx := hash << 1
    gradX := GRADIENTS_2D[idx]
    gradY := GRADIENTS_2D[idx+1]

    // Return the dot product: xd*gx + yd*gy.
    return xd*gradX + yd*gradY
}
