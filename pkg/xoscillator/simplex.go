package xoscillator

// --- Simplex Implementation Constants ---
const (
    // F2 is 0.5 * (sqrt(3.0) - 1.0)
    F2 = 0.3660254037844386
    // G2 is (3.0 - sqrt(3.0)) / 6.0
    G2 = 0.21132486540518713
    // H2 is 2.0 * G2 - 1.0
    H2 = -0.5773502691896257
    // SimplexNormalization scales the raw Simplex sum back to roughly [-1.0, 1.0].
    SimplexNormalization = 99.20689070704672
)

// fastFloor implements a fast floor operation using int casting.
func fastFloor(v float64) int {
    if v >= 0 {
        return int(v)
    }
    // For negative numbers, int(v) truncates towards zero.
    // We need to subtract 1 to floor correctly (e.g., -1.1 -> -2).
    floorV := int(v)
    if float64(floorV) == v {
        return floorV
    }
    return floorV - 1
}

// singleSimplex computes 2D Simplex noise for a given seed and coordinate (x, y).
func singleSimplex(normalize bool, seed int, x, y float64) float64 {
    // Skew the input space to determine which cell of the simplex grid we're in.
    t := (x + y) * F2
    i := fastFloor(x + t)
    j := fastFloor(y + t)

    // Unskew the cell origin back to (X0, Y0) in (x, y) space.
    t = float64(i+j) * G2
    X0 := float64(i) - t
    Y0 := float64(j) - t

    // The distances from the cell origin (X0, Y0).
    x0 := x - X0
    y0 := y - Y0

    // Determine which simplex we are in (the upper-right triangle or lower-left).
    var i1, j1 int
    if x0 > y0 {
        i1 = 1
        j1 = 0
    } else {
        i1 = 0
        j1 = 1
    }

    // Offsets for the middle corner (x1, y1) and last corner (x2, y2).
    x1 := x0 - float64(i1) + G2
    y1 := y0 - float64(j1) + G2
    x2 := x0 - 1.0 + H2
    y2 := y0 - 1.0 + H2

    n := 0.0

    // --- Contributions from the three corners ---

    // Contribution 1: (x0, y0)
    t = 0.5 - x0*x0 - y0*y0
    if t >= 0 {
        t *= t
        n += t * t * gradCoord2D(seed, i, j, x0, y0)
    }

    // Contribution 2: (x1, y1)
    t = 0.5 - x1*x1 - y1*y1
    if t >= 0 { // Replicating the '>' to '>=' for consistency, though it rarely matters here.
        t *= t
        n += t * t * gradCoord2D(seed, i+i1, j+j1, x1, y1)
    }

    // Contribution 3: (x2, y2)
    t = 0.5 - x2*x2 - y2*y2
    if t >= 0 {
        t *= t
        n += t * t * gradCoord2D(seed, i+1, j+1, x2, y2)
    }

    // --- Normalization and Output ---

    // Scale the output to fit within approximately [-1.0, 1.0].
    _v := SimplexNormalization * n

    // If requested, remap the range from [-1.0, 1.0] to [0.0, 1.0].
    if normalize {
        _v = (_v * 0.5) + 0.5
    }
    return _v
}

